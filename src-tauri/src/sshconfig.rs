//! OpenSSH `ssh_config` 的只读导入与无密钥导出。
//!
//! 不执行 `ProxyCommand`：那是任意本地命令，导入后自动跑会把配置文件变成代码执行入口。
//! `Match` / `Include` 也不展开，导入结果里给出警告，避免静默丢条件。

use crate::model::{expand_tilde, JumpHop, PortForward};
use crate::storage::HostItem;
use serde::Serialize;
use std::collections::{HashMap, HashSet};
use std::path::Path;

#[derive(Debug, Clone, Serialize)]
pub struct ImportPreview {
    pub hosts: Vec<HostItem>,
    pub warnings: Vec<String>,
    #[serde(rename = "sourcePath")]
    pub source_path: String,
}

struct Block {
    patterns: Vec<String>,
    values: HashMap<String, Vec<String>>,
}

pub fn default_config_path() -> std::path::PathBuf {
    dirs::home_dir()
        .unwrap_or_else(|| std::path::PathBuf::from("."))
        .join(".ssh")
        .join("config")
}

pub fn preview_ssh_config(path: Option<String>) -> Result<ImportPreview, String> {
    let source = match path {
        Some(path) if !path.trim().is_empty() => std::path::PathBuf::from(path),
        _ => default_config_path(),
    };
    let text = std::fs::read_to_string(&source)
        .map_err(|e| format!("读取 {} 失败: {}", source.display(), e))?;
    let (blocks, mut warnings) = parse_blocks(&text);
    if blocks.is_empty() {
        warnings.push("没有解析到 Host 块".into());
    }

    let aliases = concrete_aliases(&blocks);
    let mut hosts = Vec::new();
    let mut id_by_alias: HashMap<String, String> = HashMap::new();
    for alias in &aliases {
        let id = format!("sshcfg-{}", slug(alias));
        id_by_alias.insert(alias.to_ascii_lowercase(), id);
    }

    for alias in &aliases {
        let resolved = resolve_alias(alias, &blocks);
        if let Some(cmd) = resolved.get("proxycommand") {
            warnings.push(format!(
                "{} 含 ProxyCommand（{}），已忽略。请改用跳板机或 SOCKS/HTTP 代理",
                alias,
                cmd.first().map(|s| s.as_str()).unwrap_or("")
            ));
        }
        let host_name = first(&resolved, "hostname").unwrap_or_else(|| alias.clone());
        let port = first(&resolved, "port")
            .and_then(|p| p.parse().ok())
            .unwrap_or(22);
        let username = first(&resolved, "user").unwrap_or_else(|| "root".into());
        let identity = resolved
            .get("identityfile")
            .and_then(|files| files.iter().find(|f| Path::new(&expand_tilde(f)).is_file()).cloned())
            .or_else(|| resolved.get("identityfile").and_then(|files| files.first().cloned()));
        let auth_type = if identity.is_some() {
            "key"
        } else if preferred_is_keyboard(resolved.get("preferredauthentications")) {
            "keyboard"
        } else {
            "password"
        };
        let id = id_by_alias
            .get(&alias.to_ascii_lowercase())
            .cloned()
            .unwrap_or_else(|| format!("sshcfg-{}", slug(alias)));
        hosts.push(HostItem {
            id,
            name: alias.clone(),
            host: host_name,
            port,
            username,
            auth_type: auth_type.into(),
            password: None,
            private_key: identity.map(|p| expand_tilde(&p)),
            passphrase: None,
            group: "cloud".into(),
            tags: vec!["ssh-config".into()],
            os: None,
            os_name: None,
            status: None,
            ping: None,
            cpu: None,
            mem: None,
            disk: None,
            updated_at: None,
            jump_host_ids: Vec::new(),
            proxy: None,
            forwards: collect_forwards(alias, &resolved),
        });
    }

    resolve_jumps(&mut hosts, &blocks, &id_by_alias, &mut warnings);
    Ok(ImportPreview {
        hosts,
        warnings,
        source_path: source.to_string_lossy().to_string(),
    })
}

pub fn export_ssh_config(hosts: &[HostItem]) -> String {
    let by_id: HashMap<&str, &HostItem> = hosts.iter().map(|h| (h.id.as_str(), h)).collect();
    let mut out = String::from("# generated by SnailSSH — secrets are not exported\n");
    for host in hosts {
        out.push_str(&format!("\nHost {}\n", host.name.replace('\n', " ")));
        out.push_str(&format!("  HostName {}\n", host.host));
        out.push_str(&format!("  User {}\n", host.username));
        if host.port != 22 {
            out.push_str(&format!("  Port {}\n", host.port));
        }
        if host.auth_type == "key" {
            if let Some(key) = host.private_key.as_deref() {
                if is_path_like(key) {
                    out.push_str(&format!("  IdentityFile {}\n", key));
                }
            }
        }
        if host.proxy.as_ref().is_some_and(|proxy| proxy.is_active()) {
            out.push_str("  # Proxy is configured in SnailSSH and is not exported\n");
        }
        if !host.jump_host_ids.is_empty() {
            let jumps: Vec<&str> = host
                .jump_host_ids
                .iter()
                .filter_map(|id| by_id.get(id.as_str()).map(|h| h.name.as_str()))
                .collect();
            if !jumps.is_empty() {
                out.push_str(&format!("  ProxyJump {}\n", jumps.join(",")));
            }
        }
        for forward in &host.forwards {
            if !forward.enabled {
                continue;
            }
            match forward.kind.as_str() {
                "local" => out.push_str(&format!(
                    "  LocalForward {}:{} {}:{}\n",
                    forward.bind_host, forward.bind_port, forward.target_host, forward.target_port
                )),
                "remote" => out.push_str(&format!(
                    "  RemoteForward {}:{} {}:{}\n",
                    forward.bind_host, forward.bind_port, forward.target_host, forward.target_port
                )),
                "dynamic" => out.push_str(&format!(
                    "  DynamicForward {}:{}\n",
                    forward.bind_host, forward.bind_port
                )),
                _ => {}
            }
        }
    }
    out
}

fn resolve_jumps(
    hosts: &mut Vec<HostItem>,
    blocks: &[Block],
    id_by_alias: &HashMap<String, String>,
    warnings: &mut Vec<String>,
) {
    let alias_of: HashMap<String, String> = hosts
        .iter()
        .map(|h| (h.name.to_ascii_lowercase(), h.id.clone()))
        .collect();
    for host in hosts.iter_mut() {
        let resolved = resolve_alias(&host.name, blocks);
        let Some(raw) = first(&resolved, "proxyjump") else {
            continue;
        };
        let mut ids = Vec::new();
        for token in raw.split(',') {
            let token = token.trim();
            if token.is_empty() {
                continue;
            }
            if let Some(id) = id_by_alias
                .get(&token.to_ascii_lowercase())
                .or_else(|| alias_of.get(&token.to_ascii_lowercase()))
            {
                ids.push(id.clone());
                continue;
            }
            if let Some(inline) = parse_jump_token(token) {
                let synthetic_id = format!(
                    "sshcfg-jump-{}",
                    slug(&format!("{}@{}:{}", inline.username, inline.host, inline.port))
                );
                if !ids.contains(&synthetic_id) {
                    warnings.push(format!(
                        "{} 的跳板 {} 不是配置里的 Host 别名，已生成一条待补凭证的主机",
                        host.name, token
                    ));
                    ids.push(synthetic_id.clone());
                    // 先记下，循环结束后再插入，避免在迭代 hosts 时改长度
                    host.tags.push(format!("pending-jump:{}", synthetic_id));
                    host.tags.push(format!(
                        "pending-jump-spec:{}|{}|{}|{}",
                        synthetic_id, inline.username, inline.host, inline.port
                    ));
                }
            } else {
                warnings.push(format!("{} 的 ProxyJump 无法解析: {}", host.name, token));
            }
        }
        host.jump_host_ids = ids;
    }

    let mut extra = Vec::new();
    let existing: HashSet<String> = hosts.iter().map(|h| h.id.clone()).collect();
    for host in hosts.iter() {
        for tag in &host.tags {
            let Some(spec) = tag.strip_prefix("pending-jump-spec:") else {
                continue;
            };
            let mut parts = spec.split('|');
            let Some(id) = parts.next() else { continue };
            if existing.contains(id) || extra.iter().any(|h: &HostItem| h.id == id) {
                continue;
            }
            let username = parts.next().unwrap_or("root");
            let addr = parts.next().unwrap_or("");
            let port = parts.next().and_then(|p| p.parse().ok()).unwrap_or(22);
            extra.push(HostItem {
                id: id.into(),
                name: format!("jump-{}", addr),
                host: addr.into(),
                port,
                username: username.into(),
                auth_type: "key".into(),
                password: None,
                private_key: None,
                passphrase: None,
                group: "cloud".into(),
                tags: vec!["ssh-config".into(), "jump".into()],
                os: None,
                os_name: None,
                status: None,
                ping: None,
                cpu: None,
                mem: None,
                disk: None,
                updated_at: None,
                jump_host_ids: Vec::new(),
                proxy: None,
                forwards: Vec::new(),
            });
        }
    }
    for host in hosts.iter_mut() {
        host.tags
            .retain(|tag| !tag.starts_with("pending-jump"));
    }
    hosts.extend(extra);
}

fn collect_forwards(alias: &str, values: &HashMap<String, Vec<String>>) -> Vec<PortForward> {
    let mut out = Vec::new();
    for (index, raw) in values.get("localforward").into_iter().flatten().enumerate() {
        if let Some((bind_host, bind_port, target_host, target_port)) = parse_forward_pair(raw) {
            out.push(PortForward {
                id: format!("{}-l-{}", slug(alias), index + 1),
                kind: "local".into(),
                bind_host,
                bind_port,
                target_host,
                target_port,
                enabled: true,
            });
        }
    }
    for (index, raw) in values.get("remoteforward").into_iter().flatten().enumerate() {
        if let Some((bind_host, bind_port, target_host, target_port)) = parse_forward_pair(raw) {
            out.push(PortForward {
                id: format!("{}-r-{}", slug(alias), index + 1),
                kind: "remote".into(),
                bind_host,
                bind_port,
                target_host,
                target_port,
                enabled: true,
            });
        }
    }
    for (index, raw) in values.get("dynamicforward").into_iter().flatten().enumerate() {
        if let Some((bind_host, bind_port)) = parse_bind_only(raw) {
            out.push(PortForward {
                id: format!("{}-d-{}", slug(alias), index + 1),
                kind: "dynamic".into(),
                bind_host,
                bind_port,
                target_host: String::new(),
                target_port: 0,
                enabled: true,
            });
        }
    }
    out
}

fn parse_blocks(text: &str) -> (Vec<Block>, Vec<String>) {
    let mut warnings = Vec::new();
    let mut blocks = Vec::new();
    let mut current: Option<Block> = None;
    let mut saw_match = false;
    let mut saw_include = false;
    for raw_line in text.lines() {
        let line = strip_comment(raw_line).trim().to_string();
        if line.is_empty() {
            continue;
        }
        let Some((key, rest)) = split_keyword(&line) else {
            continue;
        };
        let key_l = key.to_ascii_lowercase();
        if key_l == "host" {
            if let Some(block) = current.take() {
                blocks.push(block);
            }
            current = Some(Block {
                patterns: tokenize(&rest),
                values: HashMap::new(),
            });
            continue;
        }
        if key_l == "match" && !saw_match {
            warnings.push("Match 块未导入，条件主机请手工补一条".into());
            saw_match = true;
        }
        if key_l == "include" && !saw_include {
            warnings.push("Include 未展开，被引用的配置文件需要单独导入".into());
            saw_include = true;
        }
        if let Some(block) = current.as_mut() {
            block.values.entry(key_l).or_default().push(rest);
        }
    }
    if let Some(block) = current {
        blocks.push(block);
    }
    (blocks, warnings)
}

fn concrete_aliases(blocks: &[Block]) -> Vec<String> {
    let mut seen = HashSet::new();
    let mut out = Vec::new();
    for block in blocks {
        for pattern in &block.patterns {
            if pattern.starts_with('!') || pattern.contains('*') || pattern.contains('?') {
                continue;
            }
            let key = pattern.to_ascii_lowercase();
            if seen.insert(key) {
                out.push(pattern.clone());
            }
        }
    }
    out
}

fn resolve_alias(alias: &str, blocks: &[Block]) -> HashMap<String, Vec<String>> {
    let mut merged: HashMap<String, Vec<String>> = HashMap::new();
    for block in blocks {
        if !host_matches(&block.patterns, alias) {
            continue;
        }
        for (key, values) in &block.values {
            let slot = merged.entry(key.clone()).or_default();
            if is_append_key(key) {
                for value in values {
                    if !slot.iter().any(|existing| existing == value) {
                        slot.push(value.clone());
                    }
                }
            } else if slot.is_empty() {
                slot.extend(values.iter().cloned());
            }
        }
    }
    merged
}

fn is_append_key(key: &str) -> bool {
    matches!(
        key,
        "identityfile" | "localforward" | "remoteforward" | "dynamicforward" | "certificatefile"
    )
}

fn host_matches(patterns: &[String], alias: &str) -> bool {
    let mut matched = false;
    for pattern in patterns {
        let negated = pattern.starts_with('!');
        let body = if negated { &pattern[1..] } else { pattern.as_str() };
        let hit = wildcard(body, alias);
        if negated && hit {
            return false;
        }
        if !negated && hit {
            matched = true;
        }
    }
    matched
}

fn wildcard(pattern: &str, value: &str) -> bool {
    let p: Vec<char> = pattern.chars().flat_map(|c| c.to_lowercase()).collect();
    let v: Vec<char> = value.chars().flat_map(|c| c.to_lowercase()).collect();
    let (mut pi, mut vi) = (0usize, 0usize);
    let (mut star, mut mark) = (None, 0usize);
    while vi < v.len() {
        if pi < p.len() && (p[pi] == '?' || p[pi] == v[vi]) {
            pi += 1;
            vi += 1;
        } else if pi < p.len() && p[pi] == '*' {
            star = Some(pi);
            mark = vi;
            pi += 1;
        } else if let Some(s) = star {
            pi = s + 1;
            mark += 1;
            vi = mark;
        } else {
            return false;
        }
    }
    while pi < p.len() && p[pi] == '*' {
        pi += 1;
    }
    pi == p.len()
}

fn preferred_is_keyboard(values: Option<&Vec<String>>) -> bool {
    let Some(raw) = values.and_then(|v| v.first()) else {
        return false;
    };
    let methods: Vec<&str> = raw.split(',').map(str::trim).filter(|s| !s.is_empty()).collect();
    methods.iter().any(|m| m.eq_ignore_ascii_case("keyboard-interactive"))
        && !methods.iter().any(|m| m.eq_ignore_ascii_case("publickey"))
}

fn first(values: &HashMap<String, Vec<String>>, key: &str) -> Option<String> {
    values.get(key).and_then(|v| v.first()).map(|s| s.trim().to_string()).filter(|s| !s.is_empty())
}

fn parse_jump_token(token: &str) -> Option<JumpHop> {
    let token = token.trim();
    if token.is_empty() || token.contains('*') {
        return None;
    }
    let (user, hostport) = match token.split_once('@') {
        Some((user, rest)) => (user.to_string(), rest),
        None => ("root".to_string(), token),
    };
    let (host, port) = split_host_port(hostport, 22)?;
    Some(JumpHop {
        host,
        port,
        username: user,
        auth_type: "key".into(),
        password: None,
        private_key: None,
        passphrase: None,
        trust_host_key: false,
    })
}

fn parse_forward_pair(raw: &str) -> Option<(String, u16, String, u16)> {
    let tokens = tokenize(raw);
    if tokens.len() == 1 {
        let (left, right) = tokens[0].split_once(' ')?;
        let (bind_host, bind_port) = split_host_port(left, 0)?;
        let (target_host, target_port) = split_host_port(right, 0)?;
        return Some((bind_host, bind_port, target_host, target_port));
    }
    if tokens.len() >= 2 {
        let (bind_host, bind_port) = split_host_port(&tokens[0], 0)?;
        let (target_host, target_port) = split_host_port(&tokens[1], 0)?;
        return Some((bind_host, bind_port, target_host, target_port));
    }
    None
}

fn parse_bind_only(raw: &str) -> Option<(String, u16)> {
    let token = tokenize(raw).into_iter().next()?;
    split_host_port(&token, 0).or_else(|| token.parse().ok().map(|port| ("127.0.0.1".into(), port)))
}

fn split_host_port(raw: &str, default_port: u16) -> Option<(String, u16)> {
    let raw = raw.trim();
    if let Some(rest) = raw.strip_prefix('[') {
        let (host, port) = rest.split_once("]:")?;
        let port = port.parse().ok()?;
        return Some((host.to_string(), port));
    }
    if let Some((host, port)) = raw.rsplit_once(':') {
        if !host.is_empty() && !host.contains(':') {
            if let Ok(port) = port.parse() {
                return Some((host.to_string(), port));
            }
        }
    }
    if default_port == 0 {
        return None;
    }
    if raw.is_empty() {
        return None;
    }
    Some((raw.to_string(), default_port))
}

fn split_keyword(line: &str) -> Option<(String, String)> {
    let mut parts = line.splitn(2, char::is_whitespace);
    let key = parts.next()?.trim();
    if key.is_empty() {
        return None;
    }
    let rest = parts.next().unwrap_or("").trim().to_string();
    Some((key.to_string(), rest))
}

fn tokenize(raw: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut buf = String::new();
    let mut quote: Option<char> = None;
    for ch in raw.chars() {
        match quote {
            Some(q) if ch == q => quote = None,
            Some(_) => buf.push(ch),
            None if ch == '"' || ch == '\'' => quote = Some(ch),
            None if ch.is_whitespace() => {
                if !buf.is_empty() {
                    out.push(std::mem::take(&mut buf));
                }
            }
            None => buf.push(ch),
        }
    }
    if !buf.is_empty() {
        out.push(buf);
    }
    out
}

fn strip_comment(line: &str) -> &str {
    let mut quote: Option<char> = None;
    let chars: Vec<char> = line.chars().collect();
    for (index, ch) in chars.iter().enumerate() {
        match quote {
            Some(q) if *ch == q => quote = None,
            Some(_) => {}
            None if *ch == '"' || *ch == '\'' => quote = Some(*ch),
            None if *ch == '#' => {
                let boundary = index == 0 || chars[index - 1].is_whitespace();
                if boundary {
                    return line.split_at(line.char_indices().nth(index).map(|(i, _)| i).unwrap_or(0)).0;
                }
            }
            None => {}
        }
    }
    line
}

fn slug(raw: &str) -> String {
    let mut out = String::new();
    for ch in raw.chars() {
        if ch.is_ascii_alphanumeric() || ch == '-' || ch == '_' {
            out.push(ch.to_ascii_lowercase());
        } else if !out.ends_with('-') {
            out.push('-');
        }
    }
    let out = out.trim_matches('-').to_string();
    if out.is_empty() {
        "host".into()
    } else {
        out.chars().take(48).collect()
    }
}

fn is_path_like(value: &str) -> bool {
    let value = value.trim();
    !value.contains('\n')
        && !value.contains("BEGIN ")
        && (value.contains('/') || value.contains('\\') || value.starts_with('~'))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_host_jump_and_forwards() {
        let text = r#"
Host *
  User ubuntu
  IdentityFile ~/.ssh/id_ed25519

Host bastion
  HostName 10.0.0.1
  User jump

Host app
  HostName 10.1.0.8
  Port 2222
  ProxyJump bastion
  LocalForward 127.0.0.1:5432 127.0.0.1:5432
  DynamicForward 1080
"#;
        let (blocks, warnings) = parse_blocks(text);
        assert!(warnings.is_empty());
        let resolved = resolve_alias("app", &blocks);
        assert_eq!(first(&resolved, "hostname").as_deref(), Some("10.1.0.8"));
        assert_eq!(first(&resolved, "user").as_deref(), Some("ubuntu"));
        assert_eq!(first(&resolved, "port").as_deref(), Some("2222"));
        assert_eq!(first(&resolved, "proxyjump").as_deref(), Some("bastion"));
        assert!(resolved.get("localforward").is_some());
        assert_eq!(concrete_aliases(&blocks), vec!["bastion", "app"]);
    }

    #[test]
    fn host_match_honors_negation() {
        assert!(host_matches(&["*.example.com".into(), "!skip.example.com".into()], "api.example.com"));
        assert!(!host_matches(&["*.example.com".into(), "!skip.example.com".into()], "skip.example.com"));
    }

    #[test]
    fn split_host_port_keeps_bracketed_ipv6() {
        let (host, port) = split_host_port("[2001:db8::1]:2222", 22).unwrap();
        assert_eq!(host, "2001:db8::1");
        assert_eq!(port, 2222);
    }
}
